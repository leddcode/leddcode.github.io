function evaluateMath(expr) {
    expr = expr.replace(/\s+/g, '');
    let pos = 0;

    function parseExpression() {
        let left = parseTerm();
        while (pos < expr.length) {
            let op = expr[pos];
            if (op === '+' || op === '-') {
                pos++;
                let right = parseTerm();
                if (op === '+') left += right;
                else left -= right;
            } else {
                break;
            }
        }
        return left;
    }

    function parseTerm() {
        let left = parseFactor();
        while (pos < expr.length) {
            let op = expr[pos];
            if (op === '*' || op === '/') {
                pos++;
                let right = parseFactor();
                if (op === '*') left *= right;
                else left /= right;
            } else {
                break;
            }
        }
        return left;
    }

    function parseFactor() {
        if (pos >= expr.length) throw new Error("Unexpected end of expression");
        let char = expr[pos];
        if (char === '(') {
            pos++;
            let val = parseExpression();
            if (expr[pos] !== ')') throw new Error("Expected ')'");
            pos++;
            return val;
        } else if (char === '-' || char === '+') {
            pos++;
            let val = parseFactor();
            return char === '-' ? -val : val;
        } else {
            return parseNumber();
        }
    }

    function parseNumber() {
        let start = pos;
        while (pos < expr.length && (/[0-9.]/.test(expr[pos]))) {
            pos++;
        }
        if (start === pos) throw new Error("Expected number");
        let numStr = expr.substring(start, pos);
        if (numStr.split('.').length > 2) throw new Error("Invalid number");
        return parseFloat(numStr);
    }

    let result = parseExpression();
    if (pos < expr.length) throw new Error("Unexpected character at " + pos);
    return result;
}

