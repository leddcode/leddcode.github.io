        let results = vectorDb.slice(-3).reverse();
        let html = `<div style="border: 1px dashed var(--command-color); padding: 10px; margin: 10px 0;"><h3 style="margin-top: 0; color: var(--command-color);">/// SEMANTIC SEARCH RESULTS</h3>`;
